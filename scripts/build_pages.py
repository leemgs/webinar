"""Generate the GitHub Pages HTML: one page per menu, each with its own URL.

    docs/dashboard/index.html   → https://leemgs.github.io/webinar/dashboard/
    docs/calendar/index.html    → https://leemgs.github.io/webinar/calendar/
    docs/list/index.html        → https://leemgs.github.io/webinar/list/
    docs/index.html             → forwards to calendar/ (the default view)

Every page carries only its own view; the shared header, menu and footer live
here once. Run `python scripts/build_pages.py` after editing this file
(tests/test_pages.py fails when the committed pages are out of date).
"""
from __future__ import annotations

import sys
from html import escape
from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent / "docs"
ASSET_VERSION = 8  # bump to bust browser caches of assets/app.js + style.css

# (key, menu label, page title, description)
VIEWS = [
    ("dashboard", "대시보드", "대시보드", "국내 IT 웨비나 통계 대시보드 — 사이트별·기술 종목별·월별 웨비나 추이"),
    ("calendar", "달력", "웨비나 달력", "국내 IT 웨비나 월별 일정 달력과 경품 정보"),
    ("list", "목록", "웨비나 목록", "국내 IT 웨비나 일정 목록(날짜순)과 경품 정보"),
]
DEFAULT_VIEW = "calendar"

SITES = [  # (name, color, url) — the "웨비나 사이트 바로가기" links
    ("올쇼TV", "#e8590c", "https://www.allshowtv.com"),
    ("쉐어드IT", "#2f9e44", "https://www.sharedit.co.kr/posts?post_type_id=4"),
    ("DD튜브", "#1971c2", "https://www.ddtube.co.kr"),
    ("e4ds", "#9c36b5", "https://www.e4ds.com/webinar.asp"),
    ("토크아이티", "#e8478b", "https://talkit.tv/main/webinars/upcoming"),
    ("두비즈", "#0c8599", "https://dubiz.co.kr/onoffmix/"),
    ("CLOIT:ON", "#f08c00", "https://webinar.cloit.com"),
    ("채널온TV", "#6741d9", "https://chontv.com"),
]

FILTERS = """
      <div class="filters">
        <div id="source-filters" class="chip-group" aria-label="출처 필터"></div>
        <div id="prize-filters" class="chip-group" aria-label="경품 필터"></div>
      </div>"""

SECTIONS = {
    "dashboard": """
    <section id="dashboard-view" class="view" aria-label="웨비나 통계 대시보드"></section>""",
    "calendar": """
    <section id="calendar-view" class="view" aria-label="웨비나 달력">
      <div class="cal-nav">
        <button id="prev-month" aria-label="이전 달">‹</button>
        <h2 id="cal-title"></h2>
        <button id="next-month" aria-label="다음 달">›</button>
        <button id="today-btn" class="today-btn">오늘</button>
      </div>
      <div class="cal-weekdays">
        <span>일</span><span>월</span><span>화</span><span>수</span><span>목</span><span>금</span><span>토</span>
      </div>
      <div id="calendar-grid" class="cal-grid"></div>
    </section>""",
    "list": """
    <section id="list-view" class="view" aria-label="웨비나 목록"></section>""",
}


def page(view: str) -> str:
    root = "../"
    _, label, title, desc = next(v for v in VIEWS if v[0] == view)
    menu = "\n".join(
        f'        <a href="{root}{key}/"'
        + (' class="active" aria-current="page"' if key == view else "")
        + f">{name}</a>"
        for key, name, _, _ in VIEWS
    )
    sites = "\n".join(
        f'          <a class="site-link" style="--site-color:{color}" href="{escape(url)}" target="_blank"'
        f' rel="noopener noreferrer"><span class="site-link-dot"></span>{name} <span aria-hidden="true">↗</span></a>'
        for name, color, url in SITES
    )
    return f"""<!DOCTYPE html>
<!-- generated by scripts/build_pages.py — edit that file, not this one -->
<html lang="ko">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>{title} · 웨비나 허브</title>
  <meta name="description" content="{escape(desc)} (올쇼TV, 쉐어드IT, DD튜브, e4ds, 토크아이티, 두비즈, CLOIT:ON, 채널온TV)" />
  <link rel="stylesheet" href="{root}assets/style.css?v={ASSET_VERSION}" />
</head>
<body data-view="{view}" data-root="{root}">
  <header class="site-header">
    <div class="wrap">
      <div class="brand">
        <a class="brand-link" href="{root}{DEFAULT_VIEW}/" title="웨비나 허브 홈">
          <h1>📡 웨비나 허브</h1>
        </a>
        <p class="tagline">국내 IT 웨비나 월별 일정 · 경품 정보</p>
      </div>
      <div class="header-meta">
        <div class="ics-box">
          <a class="ics-link" href="{root}webinars.ics" title="구글 캘린더에서 URL로 구독">📅 캘린더 구독(ICS)</a>
          <button id="ics-help" class="help-btn" type="button" aria-label="구글 캘린더 구독 방법 도움말" title="구글 캘린더 구독 방법">?</button>
        </div>
        <span id="updated" class="updated"></span>
      </div>
    </div>
  </header>

  <main class="wrap">
    <section class="controls">
      <nav class="site-directory" aria-labelledby="site-directory-title">
        <span id="site-directory-title" class="site-directory-title">🔗 웨비나 사이트 바로가기</span>
        <div id="site-links" class="site-links">
{sites}
        </div>
      </nav>

      <nav class="view-toggle" aria-label="보기 메뉴">
{menu}
      </nav>
{FILTERS if view != "dashboard" else ""}
    </section>
{SECTIONS[view]}

    <p id="empty-state" class="empty hidden">표시할 웨비나가 없습니다.</p>
  </main>

  <div id="modal" class="modal hidden" role="dialog" aria-modal="true">
    <div class="modal-backdrop" data-close></div>
    <div class="modal-card">
      <button class="modal-close" data-close aria-label="닫기">×</button>
      <div id="modal-body"></div>
    </div>
  </div>

  <footer class="site-footer">
    <div class="wrap">
      <p>매일 자동 수집 · <a href="https://github.com/leemgs/webinar" id="repo-link">webinar</a></p>
      <p class="disclaimer">일정·경품 정보는 각 사이트 기준이며 변경될 수 있습니다. 정확한 내용은 원문 링크에서 확인하세요.</p>
    </div>
  </footer>

  <script src="{root}assets/app.js?v={ASSET_VERSION}"></script>
</body>
</html>
"""


def root_redirect() -> str:
    target = f"{DEFAULT_VIEW}/"
    return f"""<!DOCTYPE html>
<!-- generated by scripts/build_pages.py — edit that file, not this one -->
<html lang="ko">
<head>
  <meta charset="UTF-8" />
  <title>웨비나 허브</title>
  <meta http-equiv="refresh" content="0; url={target}" />
  <link rel="canonical" href="{target}" />
  <script>location.replace("{target}" + location.search + location.hash);</script>
</head>
<body>
  <p><a href="{target}">웨비나 달력으로 이동</a> · <a href="dashboard/">대시보드</a> · <a href="list/">목록</a></p>
</body>
</html>
"""


def outputs() -> dict[Path, str]:
    out = {DOCS / "index.html": root_redirect()}
    for key, *_ in VIEWS:
        out[DOCS / key / "index.html"] = page(key)
    return out


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for path, html in outputs().items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != html:
                stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(html, encoding="utf-8")
        print(f"wrote {path.relative_to(DOCS.parent)}")
    if stale:
        print("out of date (run python scripts/build_pages.py):", *map(str, stale), sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
